insert into public.app_governance(user_id, governance_role, created_by)
select p.id, 'ADMIN', owner_row.user_id
from public.profiles p
join auth.users u on u.id = p.id
cross join lateral (
  select user_id from public.app_governance where governance_role='OWNER' limit 1
) owner_row
where p.ativo = true
  and p.perfil = 'admin'
  and lower(u.email) <> lower('filipecarneirodasilva@gmail.com')
on conflict (user_id) do update
  set governance_role = case when public.app_governance.governance_role='OWNER' then 'OWNER' else 'ADMIN' end,
      updated_at = now();